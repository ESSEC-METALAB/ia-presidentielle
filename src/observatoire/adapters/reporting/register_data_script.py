"""Register -> `data.js` for the public register site (web/registre/, `window.IA2027_DATA`).

The shape is the site prototype's: axes, candidates, claims, corrections. Every value
comes from configuration or from a stored document; the annotation adds only the
dimension, the quote it located and the descriptive notes that passed the gates.
"""

import json
from datetime import date
from urllib.parse import urlsplit

from observatoire.domain.annotation import Dimension
from observatoire.domain.register import Register, RegisterCandidate, RegisterEntry

# Source kind -> the site's statement kind. Describes the medium, which is a fact; the
# genre (speech, interview, release) would be an editorial call, made at review.
_KIND_OF_SOURCE = {
    "assemblee_nationale": "seance",
    "rss": "article",
    "sitemap": "article",
    "page": "page",
    "pdf": "pdf",
}
_HEADER = (
    "// GENERATED by `observatoire register` from data/observatoire.db. Do not edit:\n"
    "// rebuild instead. Real quotes, located in the stored source texts by code.\n"
)


def _iso(day: date | None) -> str | None:
    return day.isoformat() if day else None


def _axis(dimension: Dimension) -> dict[str, object]:
    return {
        "id": dimension.id,
        "fr": dimension.label_fr,
        "en": dimension.label_en,
        "descFr": " ".join(dimension.definition_fr.split()),
        "descEn": " ".join(dimension.definition_en.split()),
    }


def _candidate(listed: RegisterCandidate, pending: int) -> dict[str, object]:
    person = listed.candidate
    return {
        "id": person.id,
        "first": person.given_name,
        "last": person.surname,
        "party": person.party,
        "partyShort": person.party_short or person.party,
        "tracked": listed.monitored,
        # AI passages nobody has annotated yet: the site says "en attente" for this
        # candidate's empty cells instead of "aucune position identifiée".
        "pending": pending,
        "sources": [{"fr": s.label, "en": s.label, "url": s.url} for s in listed.sources],
    }


def _claim(entry: RegisterEntry) -> dict[str, object]:
    statement, document, source = entry.annotation, entry.document, entry.source
    host = urlsplit(document.url).hostname or document.url
    return {
        "id": statement.id,
        "cand": document.candidate_id,
        "axis": statement.dimension,
        "date": _iso(document.published_on),
        "tier": int(document.trust_level),
        "tierConfirmed": source.trust_confirmed,
        "kind": _KIND_OF_SOURCE.get(source.kind, "article"),
        "quote": statement.quote,
        "gloss": statement.gloss_en,
        "summaryFr": statement.summary_fr,
        "summaryEn": statement.summary_en,
        "contextFr": statement.context_fr,
        "contextEn": statement.context_en,
        "sourceLabel": f"{host} — {document.title or source.label}",
        "sourceUrl": document.url,
        "archiveUrl": document.archive_url,
        "archiveDate": _iso(document.archived_on),
        # From a cross-verified edition (config/register.yaml), or automatic gates only.
        "verified": entry.verified,
    }


class RegisterDataScript:
    def render(self, register: Register) -> str:
        data = {
            "generated": register.generated_at.date().isoformat(),
            "windowStart": _iso(register.window_start),
            "annotators": list(register.annotators),
            "reviewed": False,  # no statement has been through editorial review yet
            "pending": sum(register.pending.values()),
            "axes": [_axis(d) for d in register.dimensions],
            "candidates": [
                _candidate(c, register.pending.get(c.candidate.id, 0)) for c in register.candidates
            ],
            "claims": [_claim(e) for e in register.entries],
            "corrections": [],
        }
        body = json.dumps(data, ensure_ascii=False, indent=1)
        return f"{_HEADER}window.IA2027_DATA = {body};\n"
